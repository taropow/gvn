const wchar_t *command_name(unsigned id) {
    const auto &commands = command_catalog();
    const auto it =
        std::find_if(commands.begin(), commands.end(), [=](const auto &entry) { return entry.id == id; });
    return it == commands.end() ? L"不明な機能" : it->name.c_str();
}
